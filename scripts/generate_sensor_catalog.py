#!/usr/bin/env python3
"""Compile reviewed catalogue records to Kotlin; no network or main PDF engine access."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "sensor-catalog/expanded-1.0.10.json"
OUTPUT = ROOT / "app/src/main/java/com/example/datasheetanalyzer/features/sensoralternatives/ExpandedSensorCatalog.kt"
FIELDS = ("SCOPE", "MEASUREMENT", "SUPPLY", "INTERFACE", "RANGE", "ACCURACY", "PACKAGE", "PINOUT")

def literal(value):
    # JSON escaping matches Kotlin strings, except Kotlin's interpolation marker.
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")

def render():
    profiles = json.loads(INPUT.read_text())['profiles']
    assert len({p['code'] for p in profiles}) == len(profiles)
    output = ["package com.example.datasheetanalyzer.features.sensoralternatives", "",
              "// Generated by scripts/generate_sensor_catalog.py from reviewed manufacturer records.",
              "// Update sensor-catalog/expanded-1.0.10.json; manufacturer PDFs are not bundled.",
              "internal object ExpandedSensorCatalog {", "    val profiles: List<SensorProfile> = buildList {"]
    chunks = [profiles[i:i+20] for i in range(0,len(profiles),20)]
    output += [f"        addAll(batch{i}())" for i in range(len(chunks))]
    output += ["    }"]
    for i,batch in enumerate(chunks):
        output += [f"    private fun batch{i}(): List<SensorProfile> = listOf("]
        for p in batch:
            s=p['source']
            assert set(p['facts']) == set(FIELDS)
            assert all(all(1<=page<=s['page_count'] for page in p['facts'][f]['pages']) for f in FIELDS)
            measurements=','.join('SensorMeasurement.'+v for v in p['measurements'])
            interfaces=','.join('SensorInterface.'+v for v in p['interfaces'])
            output += [f"        SensorProfile({literal(p['code'])},{literal(p['manufacturer'])},setOf(),",
                       f"            setOf({measurements}),setOf({interfaces}),OperatingVoltage({p['voltage'][0]},{p['voltage'][1]}),",
                       f"            SensorSource({literal(s['url'])},{literal(s['revision'])},{s['page_count']},{literal(s['sha256'])}),mapOf("]
            for f in FIELDS:
                fact=p['facts'][f];pages=','.join(map(str,fact['pages']))
                output += [f"                SensorField.{f} to SensorFact({literal(fact['text'])},listOf({pages})),"]
            bands=','.join(f"OperatingVoltage({lo},{hi})" for lo,hi in p['additional_voltage_ranges'])
            axes=','.join(f"SensorMeasurement.{key} to {value}" for key,value in p['axis_counts'].items())
            output += [f"            ),additionalVoltageRanges=listOf({bands}),axisCounts=mapOf({axes})),"]
        output += ["    )"]
    output += ["}", ""]
    return '\n'.join(output)

if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    content=render()
    if args.check:
        if OUTPUT.read_text()!=content:raise SystemExit('Compiled catalogue differs from reviewed records')
        print('Catalogue source and generated Kotlin match')
    else:
        OUTPUT.write_text(content)
        print('Generated expanded catalogue')
